from pydantic import BaseModel, Field
from typing import Dict, Any

class RepoBrief(BaseModel):
    """
    Final output schema containing GitHub API metadata and the agent-generated markdown brief.
    """
    github_metadata: Dict[str, Any] = Field(
        default_factory=dict,
        description=(
            "All GitHub API metadata: stars, forks, watchers, open_issues, topics, homepage, "
            "license, created_at, updated_at, pushed_at, visibility, is_fork, archived, "
            "contributors_count, latest_release, size_kb, has_wiki, has_discussions, etc."
        )
    )
    repo_brief_markdown: str = Field(
        description="A highly accurate and comprehensive brief of the repository in Markdown format generated by the LangChain agent."
    )

